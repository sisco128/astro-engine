/**
 * Queries JPL Horizons for apparent geocentric ecliptic longitude/latitude and
 * writes a reference file the golden suite asserts against.
 *
 * This is Tier A of the golden suite's three tiers of truth, and it is the only
 * one that is genuinely independent. `swetest` shares the Swiss Ephemeris C
 * source, so it cannot catch a wrong SEFLG_* combination or a bad data file —
 * it would make the same mistake. Horizons can.
 *
 * Run deliberately, review the diff, commit the result. Never in CI: the golden
 * suite must not depend on a third party being up, and a reference value that
 * silently refreshes is not a reference value.
 *
 *   node scripts/fetch-horizons.mjs <output.json> <jd> [<jd> ...]
 */

import { writeFile } from 'node:fs/promises';

const API = 'https://ssd.jpl.nasa.gov/api/horizons.api';

/**
 * Horizons target codes. Note these are *barycentre-free* body codes: 199 is
 * Mercury itself, not the Mercury barycentre.
 */
const TARGETS = {
  sun: '10',
  moon: '301',
  mercury: '199',
  venus: '299',
  mars: '499',
  jupiter: '599',
  saturn: '699',
  uranus: '799',
  neptune: '899',
  pluto: '999',
};

/** QUANTITIES='31' is observer ecliptic longitude and latitude (ObsEcLon/ObsEcLat). */
async function queryOne(target, jd) {
  const params = new URLSearchParams({
    format: 'text',
    COMMAND: `'${target}'`,
    OBJ_DATA: "'NO'",
    MAKE_EPHEM: "'YES'",
    EPHEM_TYPE: "'OBSERVER'",
    CENTER: "'500@399'", // geocentre
    TLIST: String(jd),
    QUANTITIES: "'31'",
    REF_SYSTEM: "'ICRF'",
    CAL_FORMAT: "'JD'",
  });

  const response = await fetch(`${API}?${params.toString()}`);
  if (!response.ok) {
    throw new Error(`Horizons ${target} @ ${jd}: HTTP ${response.status}`);
  }

  const text = await response.text();
  const start = text.indexOf('$$SOE');
  const end = text.indexOf('$$EOE');
  if (start === -1 || end === -1) {
    throw new Error(`Horizons ${target} @ ${jd}: no ephemeris block in response`);
  }

  const row = text
    .slice(start + 5, end)
    .trim()
    .split('\n')[0];
  const fields = row.trim().split(/\s+/);
  const lon = Number(fields[1]);
  const lat = Number(fields[2]);

  if (!Number.isFinite(lon) || !Number.isFinite(lat)) {
    throw new Error(`Horizons ${target} @ ${jd}: could not parse "${row}"`);
  }

  return { lon, lat };
}

const [outPath, ...jds] = process.argv.slice(2);
if (outPath === undefined || jds.length === 0) {
  console.error('usage: node scripts/fetch-horizons.mjs <output.json> <jd> [<jd> ...]');
  process.exit(1);
}

const epochs = [];

for (const jdArg of jds) {
  const jd = Number(jdArg);
  const bodies = {};

  for (const [name, code] of Object.entries(TARGETS)) {
    process.stdout.write(`  ${name.padEnd(9)} @ JD ${jdArg} ... `);
    bodies[name] = await queryOne(code, jd);
    console.log(`${bodies[name].lon.toFixed(7)}`);
    // Horizons asks for courtesy between requests.
    await new Promise((resolve) => setTimeout(resolve, 250));
  }

  epochs.push({ jdUt: jd, bodies });
}

await writeFile(
  outPath,
  `${JSON.stringify(
    {
      $comment:
        'Generated by scripts/fetch-horizons.mjs. Tier A reference data — regenerate deliberately and review the diff. Never fetched in CI.',
      provider: 'jpl-horizons',
      quantities: 'ObsEcLon / ObsEcLat, apparent, geocentric (CENTER=500@399), ICRF',
      retrieved: new Date().toISOString().slice(0, 10),
      epochs,
    },
    null,
    2,
  )}\n`,
);

console.log(`\nwrote ${outPath} (${epochs.length} epoch(s))`);
